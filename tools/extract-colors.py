"""Extract the two dominant colors of each catalog image -> js/catalog-colors.js
Used by the 'matching products' suggestions. Re-run after adding catalog images:
    python3 tools/extract-colors.py
"""
import glob, json, os
from collections import Counter
from PIL import Image

out = {}
for path in sorted(glob.glob('images/catalog/*/*.webp')):
    im = Image.open(path).convert('RGBA')
    im.thumbnail((64, 64))
    counts = Counter()
    for r, g, b, a in im.getdata():
        if a < 200:
            continue
        counts[(r // 32, g // 32, b // 32)] += 1
    top = counts.most_common(2)
    total = sum(counts.values()) or 1
    cols = [[k[0] * 32 + 16, k[1] * 32 + 16, k[2] * 32 + 16] for k, v in top if v / total > 0.08]
    out[path.replace('images/catalog/', '')[:-5]] = cols or [[128, 128, 128]]

with open('js/catalog-colors.js', 'w') as f:
    f.write('/* generated by tools/extract-colors.py */\nwindow.CATALOG_COLORS=' + json.dumps(out, separators=(',', ':')) + ';\n')
print(len(out), 'images')
